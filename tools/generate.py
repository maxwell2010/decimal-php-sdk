"""Generate PHP bindings and a reviewable operation catalog from bundled ABI."""
import hashlib
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]

def abi_type(item):
    t = item['type']
    return '(' + ','.join(map(abi_type, item['components'])) + ')' + t[5:] if t.startswith('tuple') else t

def php_type(item):
    t = item['type']
    return 'array' if '[' in t or t.startswith('tuple') else 'bool' if t == 'bool' else 'string'

def generate():
    out = ROOT / 'src' / 'Contracts'
    out.mkdir(exist_ok=True)
    catalog = []
    for path in sorted((ROOT / 'abi').glob('*.json')):
        abi = json.loads(path.read_text())
        entries = [e for e in abi if e.get('type') == 'function']
        lines = ['<?php', 'declare(strict_types=1);', 'namespace Decimal\\Contracts;', '', '// Generated by tools/generate.py.', f'final class {path.stem} extends \\Decimal\\Contract', '{', '    public function __construct(string $address)', "    { parent::__construct($address, json_decode(file_get_contents(dirname(__DIR__, 2) . '/abi/" + path.name + "'), true, 512, JSON_THROW_ON_ERROR)); }"]
        for e in entries:
            sig = e['name'] + '(' + ','.join(map(abi_type, e['inputs'])) + ')'
            # Suffix every method to avoid case-insensitive PHP collisions and reserved names.
            name = e['name'] + '_' + hashlib.sha256(sig.encode()).hexdigest()[:8]
            read = e['stateMutability'] in ('view', 'pure')
            args = [f"{php_type(a)} $arg{i}" for i, a in enumerate(e['inputs'])]
            values = '[' + ', '.join(f'$arg{i}' for i in range(len(args))) + ']'
            args.insert(0, '\\Decimal\\Client $client' if read else 'string $from')
            if e['stateMutability'] == 'payable':
                args.append("string $value = '0'")
            ret = 'array' if read else '\\Decimal\\TransactionDraft'
            call = f"$this->call($client, '{sig}', {values})" if read else f"$this->draft($from, '{sig}', {values}" + (', $value)' if e['stateMutability'] == 'payable' else ')')
            lines.extend([f'    public function {name}(' + ', '.join(args) + f'): {ret}', '    { return ' + call + '; }'])
            catalog.append(dict(profile=path.stem, signature=sig, method=name, mutability=e['stateMutability']))
        lines.append('}')
        (out / (path.stem + '.php')).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    (ROOT / 'docs' / 'operations.json').write_text(json.dumps(catalog, indent=2) + '\n', newline='\n')
    hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT / 'abi').glob('*.json'))}
    (ROOT / 'docs' / 'abi-hashes.json').write_text(json.dumps(hashes, indent=2) + '\n', newline='\n')
    print(f'{len(hashes)} ABI profiles, {len(catalog)} function bindings')

if __name__ == '__main__':
    generate()
